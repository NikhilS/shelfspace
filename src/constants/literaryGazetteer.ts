export type GazetteerZoneId =
  | 'north_america'
  | 'latin_america_caribbean'
  | 'western_northern_europe'
  | 'eastern_europe_mena'
  | 'sub_saharan_africa'
  | 'asia_oceania_polar';

export type GazetteerAdminLevel = 'city' | 'state' | 'country' | 'region';

export interface GazetteerPlace {
  id: string;
  name: string;
  zone: GazetteerZoneId;
  adminLevel: GazetteerAdminLevel;
  coordinates: {lat: number; lng: number};
  context: string;
  aliases?: readonly string[];
}

